class TestBugH1TransformInversion:
    """Bug H1: whichtoinvert_inv must invert affine and composite transforms correctly."""

    def test_single_transform_inversion(self):
        # Create fixed and moving images
        arr_f = np.zeros((32, 32, 16), dtype=np.float32)
        arr_f[10:22, 10:22, 4:12] = 1.0
        fi = ants.from_numpy(arr_f, origin=(0, 0, 0), spacing=(1.0, 1.0, 1.0))
        fl = (fi > 0.5).astype("float32")

        # Transform mapping fixed to moving
        tx_f2m = ants.create_ants_transform(transform_type="AffineTransform", dimension=3)
        tx_f2m.set_parameters(np.concatenate([np.eye(3).ravel(), np.array([2.0, 0.0, 0.0])]))
        tx_f2m.set_fixed_parameters(np.array(ants.get_center_of_mass(fi)))

        # Moving image generated by tx_f2m
        mi = tx_f2m.apply_to_image(fi, fi)
        ml = (mi > 0.5).astype("float32")

        # ITK registration convention: fwdtransforms maps moving -> fixed (tx_m2f)
        tx_m2f = tx_f2m.invert()

        with tempfile.NamedTemporaryFile(suffix=".mat") as tmp:
            ants.write_transform(tx_m2f, tmp.name)

            # When whichtoinvert_inv=[True], fl is correctly mapped into moving space
            df_fix, df_mov, df_sym = compute_bidirectional_dice(
                fl, ml, fi, mi,
                fwdtransforms=[tmp.name],
                invtransforms=[tmp.name],
                whichtoinvert_inv=[True]
            )
            assert df_fix > 0.99, f"Fixed space Dice should be ~1.0, got {df_fix}"
            assert df_mov > 0.99, f"Moving space Dice should be ~1.0 with inverted transform, got {df_mov}"
            assert df_sym > 0.99

            # Default (whichtoinvert_inv=None) must also automatically set [True]
            df_fix_def, df_mov_def, df_sym_def = compute_bidirectional_dice(
                fl, ml, fi, mi,
                fwdtransforms=[tmp.name],
                invtransforms=[tmp.name],
                whichtoinvert_inv=None
            )
            assert np.isclose(df_mov, df_mov_def)

            # Passing buggy [False] inverts incorrectly and produces low moving-space Dice
            _, df_mov_bug, _ = compute_bidirectional_dice(
                fl, ml, fi, mi,
                fwdtransforms=[tmp.name],
                invtransforms=[tmp.name],
                whichtoinvert_inv=[False]
            )
            assert df_mov_bug < df_mov, "Passing [False] fails to invert affine transform"


class TestBugH2AnisotropyPreservingCapping:
    """Bug H2: cap_ants_image with deformable policy preserves native thick z-slices."""

    def test_cap_ants_image_preserves_z_slice_spacing(self):
        # Clinical CT geometry: fine in-plane (0.8x0.8 mm) with thick z-slices (2.5 mm)
        arr = np.zeros((64, 64, 30), dtype=np.float32)
        arr[20:44, 20:44, 10:20] = 1.0
        img = ants.from_numpy(arr, origin=(0, 0, 0), spacing=(0.8, 0.8, 2.5), direction=np.eye(3))

        # Under deformable policy, axes coarser than target (z=2.5mm >= target=1.5mm) remain untouched
        capped = cap_ants_image(img, max_resolution_mm=1.5, policy="deformable")

        assert capped.shape[2] == 30, f"Expected 30 z-slices, got {capped.shape[2]}"
        assert np.isclose(capped.spacing[2], 2.5), f"Expected 2.5mm z-spacing, got {capped.spacing[2]}"
        # In-plane axes must be capped
        assert capped.shape[0] < 64
        assert capped.shape[1] < 64
        assert capped.spacing[0] > 0.8

    def test_msd_prepare_image_and_label_leaves_labels_at_native_resolution(self):
        with tempfile.TemporaryDirectory() as tmp_dir:
            arr_im = np.zeros((60, 60, 20), dtype=np.float32)
            arr_im[15:45, 15:45, 5:15] = 1.0
            im = ants.from_numpy(arr_im, spacing=(0.5, 0.5, 3.0))
            lb = (im > 0.5).astype("float32")

            im_path = os.path.join(tmp_dir, "im.nii.gz")
            lb_path = os.path.join(tmp_dir, "lb.nii.gz")
            ants.image_write(im, im_path)
            ants.image_write(lb, lb_path)

            im_prep, lb_prep = _prepare_image_and_label(im_path, lb_path, max_dimension=32)
            # Label map MUST remain at native resolution (60, 60, 20)
            assert lb_prep.shape == (60, 60, 20), f"Label was improperly downsampled: {lb_prep.shape}"
            assert np.isclose(lb_prep.spacing[2], 3.0)


class TestBugH3ZeroTestLabelLeakage:
    """Bug H3: Tournament selection scores candidates via image similarity without inspecting test labels."""

    def test_tournament_selection_uses_image_similarity_not_labels(self):
        arr0 = np.zeros((32, 32, 16), dtype=np.float32)
        arr0[10:22, 10:22, 4:12] = 1.0
        im0 = ants.from_numpy(arr0, spacing=(1.0, 1.0, 1.0))

        arr1 = np.zeros((32, 32, 16), dtype=np.float32)
        arr1[12:24, 10:22, 4:12] = 1.0
        im1 = ants.from_numpy(arr1, spacing=(1.0, 1.0, 1.0))

        # compute_structural_lncc scores whole-domain similarity without ground truth test labels
        score_init = compute_structural_lncc(im0, im1, mask=None)
        score_perfect = compute_structural_lncc(im0, im0, mask=None)

        assert score_perfect > score_init
        assert np.isclose(score_perfect, 1.0)


class TestBugH4TrueHoldOutLandmarkTRE:
    """Bug H4: Target Registration Error (TRE) must be measured on hold-out points disjoint from fit inliers."""

    def test_compute_tre_on_holdout_points(self):
        pts_true = np.array([
            [10.0, 10.0, 10.0],
            [20.0, 20.0, 20.0],
            [30.0, 30.0, 30.0],
            [40.0, 40.0, 40.0],
        ], dtype=np.float32)

        # Predicted points with known 0.5 mm perturbation
        pts_pred = pts_true + np.array([0.5, 0.0, 0.0], dtype=np.float32)

        tre = compute_tre(pts_true, pts_pred)
        assert np.isclose(tre, 0.5, atol=1e-4)

    def test_disjoint_fit_and_holdout_partition(self):
        # 10 matched landmark pairs
        kpts_all = np.arange(20).reshape(10, 2)
        m_fit = kpts_all[::2]
        m_holdout = kpts_all[1::2]

        fit_indices = set(m_fit[:, 0])
        holdout_indices = set(m_holdout[:, 0])

        # Intersect must be empty (strictly disjoint sets)
        assert fit_indices.isdisjoint(holdout_indices)
        assert len(fit_indices) == 5
        assert len(holdout_indices) == 5


class TestBugH5TaskLabelSemanticsAndStratum:
    """Bug H5: Task-specific label semantics and Stratum A / Stratum B separation."""

    def test_liver_and_pancreas_parenchymal_combination(self):
        # Liver / Pancreas with parenchyma (1) and tumor (2)
        arr = np.zeros((20, 20, 10), dtype=np.float32)
        arr[5:15, 5:15, 2:8] = 1.0   # Parenchyma
        arr[8:12, 8:12, 4:6] = 2.0   # Lesion
        lbl = ants.from_numpy(arr, spacing=(1.0, 1.0, 1.0))
        img = ants.from_numpy(arr, spacing=(1.0, 1.0, 1.0))

        spec_liver = {"name": "Task03_Liver", "is_organ_task": True, "is_ct": True}
        mask = extract_surrogate_mask(img, spec_liver, raw_label=lbl)
        mask_arr = mask.numpy()

        # Both label 1 and label 2 must be included in parenchymal mask
        assert (mask_arr == 1.0).sum() == (arr > 0).sum()
        assert np.array_equal(mask_arr > 0.5, (arr == 1.0) | (arr == 2.0))

    def test_prostate_whole_gland_combination(self):
        arr = np.zeros((20, 20, 10), dtype=np.float32)
        arr[5:15, 5:15, 2:8] = 1.0   # PZ
        arr[8:12, 8:12, 4:6] = 2.0   # TZ
        lbl = ants.from_numpy(arr, spacing=(1.0, 1.0, 1.0))
        img = ants.from_numpy(arr, spacing=(1.0, 1.0, 1.0))

        spec_prostate = {"name": "Task05_Prostate", "is_organ_task": True, "is_ct": False}
        mask = extract_surrogate_mask(img, spec_prostate, raw_label=lbl)
        mask_arr = mask.numpy()
        assert np.array_equal(mask_arr > 0.5, (arr == 1.0) | (arr == 2.0))

    def test_stratum_a_and_b_task_classification(self):
        stratum_a = [s["name"] for s in TASK_SPECS if s.get("stratum") == "A"]
        stratum_b = [s["name"] for s in TASK_SPECS if s.get("stratum") == "B"]

        assert len(stratum_a) == 6, f"Expected 6 Stratum A tasks, got {len(stratum_a)}"
        assert len(stratum_b) == 4, f"Expected 4 Stratum B tasks, got {len(stratum_b)}"

        assert set(stratum_a) == {
            "Task02_Heart", "Task03_Liver", "Task04_Hippocampus",
            "Task05_Prostate", "Task07_Pancreas", "Task09_Spleen"
        }
        assert set(stratum_b) == {
            "Task01_BrainTumour", "Task06_Lung",
            "Task08_HepaticVessel", "Task10_Colon"
        }


